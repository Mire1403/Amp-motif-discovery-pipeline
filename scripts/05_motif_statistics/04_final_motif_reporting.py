def finite(s: pd.Series) -> pd.Series:
    return pd.to_numeric(s, errors="coerce").replace([np.inf, -np.inf], np.nan)


def legend_patches() -> list:
    return [mpatches.Patch(color=v, label=k, alpha=0.85)
            for k, v in PALETTE.items()]


def class_color(cls: str) -> str:
    return PALETTE.get(str(cls).strip(), "#AAAAAA")


def load_sheet(path: Path, sheet: str) -> pd.DataFrame:
    try:
        df = pd.read_excel(path, sheet_name=sheet, engine="openpyxl")
        logger.info("Loaded sheet '%s': %d rows", sheet, len(df))
        return df
    except Exception as e:
        logger.warning("Could not load sheet '%s': %s", sheet, e)
        return pd.DataFrame()

