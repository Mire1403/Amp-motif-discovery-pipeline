def analysis_summary(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    summary = (
        df.groupby(["Clustering","Tool"])
        .agg(
            n_total=("Motif","count"),
            n_sig=("Significant","sum"),
            mean_log2ER=("log2_ER", lambda x: x.replace([np.inf,-np.inf],np.nan).mean()),
            n_infinite=("ER_infinite","sum"),
            mean_length=("Motif_length","mean"),
        ).reset_index()
    )
    summary["pct_sig"] = (100 * summary["n_sig"] / summary["n_total"]).round(1)
    logger.info("\n=== Summary ===\n%s", summary.to_string(index=False))

    class_df = (
        df[df["Significant"]].groupby(["Clustering","Tool","Motif_class"])
        .size().reset_index(name="n")
    )
    return summary, class_df


def analysis_overlap(df_sig: pd.DataFrame,
                     max_mm: int = 2) -> tuple[pd.DataFrame, pd.DataFrame]:
    combo_sets = {
        (cl, tl): set(sub["Motif"].astype(str))
        for (cl, tl), sub in df_sig.groupby(["Clustering","Tool"])
    }
    exact_rows = []
    for a, b in combinations(sorted(combo_sets), 2):
        inter = combo_sets[a] & combo_sets[b]
        union = combo_sets[a] | combo_sets[b]
        exact_rows.append({
            "A": f"{a[0]}_{a[1]}", "B": f"{b[0]}_{b[1]}",
            "n_A": len(combo_sets[a]), "n_B": len(combo_sets[b]),
            "n_shared": len(inter),
            "Jaccard": round(len(inter)/len(union), 4) if union else np.nan,
            "shared_motifs": ";".join(sorted(inter)),
        })

    cons_maps = {k: extract_consensus(v) for k, v in MOTIF_FILES.items()}
    sim_rows = []
    for a, b in combinations(sorted(combo_sets), 2):
        ma = [cons_maps.get(a,{}).get(m,"") for m in combo_sets[a]]
        mb = [cons_maps.get(b,{}).get(m,"") for m in combo_sets[b]]
        ma = [x for x in ma if x]; mb = [x for x in mb if x]
        n_sim = sum(
            1 for s1 in ma if any(
                h is not None and h <= max_mm
                for h in [hamming(s1, s2) for s2 in mb])
        ) if ma and mb else np.nan
        sim_rows.append({
            "A": f"{a[0]}_{a[1]}", "B": f"{b[0]}_{b[1]}",
            "n_cons_A": len(ma), "n_cons_B": len(mb),
            "n_similar": n_sim, "max_mismatch": max_mm,
        })

    return pd.DataFrame(exact_rows), pd.DataFrame(sim_rows)


def analysis_length_meme_vs_streme(df: pd.DataFrame) -> pd.DataFrame:
    """Compare motif length between MEME and STREME, per dataset."""
    rows = []
    for cl in df["Clustering"].unique():
        meme   = df[(df["Clustering"]==cl) & (df["Tool"]=="meme")   & df["Significant"]]["Motif_length"].dropna()
        streme = df[(df["Clustering"]==cl) & (df["Tool"]=="streme") & df["Significant"]]["Motif_length"].dropna()
        if len(meme) < 2 or len(streme) < 2:
            continue
        u, p = mannwhitneyu(meme, streme, alternative="two-sided")
        d = (meme.mean() - streme.mean()) / np.sqrt(
            (meme.std()**2 + streme.std()**2) / 2)
        rows.append({
            "Clustering":         cl,
            "mean_len_meme":      round(meme.mean(),2),
            "mean_len_streme":    round(streme.mean(),2),
            "median_len_meme":    meme.median(),
            "median_len_streme":  streme.median(),
            "p_mannwhitney":      round(p, 8),
            "Cohen_d":            round(d, 4),
        })
    df_out = pd.DataFrame(rows)
    logger.info("\n=== Motif length MEME vs STREME ===\n%s", df_out.to_string(index=False))
    return df_out

