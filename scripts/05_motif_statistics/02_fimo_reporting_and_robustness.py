def load_fimo_hit_counts() -> pd.DataFrame:
    """Load raw FIMO hit counts from fimo.tsv files."""
    records = []
    for (cl, tl), fimo_dir in FIMO_AMP_DIRS.items():
        tsv = fimo_dir / "fimo.tsv"
        if not tsv.exists():
            logger.warning("fimo.tsv not found: %s", tsv)
            continue
        try:
            fimo = pd.read_csv(tsv, sep="\t", comment="#", low_memory=False)
        except Exception as e:
            logger.warning("Could not read %s: %s", tsv, e)
            continue
        if fimo.empty:
            continue

        fimo.columns = [c.strip().lower().replace("-","_") for c in fimo.columns]
        mcol = next((c for c in ["motif_id","motif_alt_id"] if c in fimo.columns), None)
        scol = next((c for c in ["sequence_name","sequence"] if c in fimo.columns), None)
        if not mcol or not scol:
            continue

        fimo["_motif"] = fimo[mcol].astype(str).map(clean_motif_name)
        fimo[scol]     = fimo[scol].astype(str).str.strip()
        total_seqs     = fimo[scol].nunique()

        for motif, grp in fimo.groupby("_motif", dropna=True):
            records.append({
                "Clustering":          cl,
                "Tool":                tl,
                "Motif":               motif,
                "Total_hits":          len(grp),
                "AMP_seqs_hit":        grp[scol].nunique(),
                "AMP_total_seqs":      total_seqs,
                "AMP_hit_pct":         round(100 * grp[scol].nunique() / total_seqs, 2)
                                       if total_seqs > 0 else np.nan,
            })
    return pd.DataFrame(records) if records else pd.DataFrame()


def classify_motif(seq: str) -> str:
    seq = str(seq); L = len(seq)
    if L == 0: return "Other"
    fC  = seq.count("C") / L
    fG  = seq.count("G") / L
    fKR = (seq.count("K") + seq.count("R")) / L
    fH  = sum(seq.count(x) for x in "AILMFWVY") / L
    if fC >= 0.25:  return "Cys-rich"
    if fG >= 0.30:  return "Gly-rich"
    if fKR >= 0.35: return "Cationic"
    if fH >= 0.60:  return "Hydrophobic"
    return "Other"


def extract_consensus(motif_file: Path) -> dict[str, str]:
    """Extract consensus sequences from MEME/STREME text output."""
    if not motif_file.exists():
        return {}
    alphabet = "ACDEFGHIKLMNPQRSTVWY"
    lines    = motif_file.read_text(errors="ignore").splitlines(True)
    result   = {}
    i = 0
    while i < len(lines):
        if lines[i].startswith("MOTIF"):
            parts    = lines[i].strip().split()
            motif_id = clean_motif_name(parts[1]) if len(parts) >= 2 else ""
            i += 1
            while i < len(lines) and "letter-probability matrix" not in lines[i]:
                i += 1
            if i >= len(lines): break
            w_match = re.search(r"w=\s*(\d+)", lines[i])
            if not w_match: i += 1; continue
            width = int(w_match.group(1)); i += 1
            matrix = []
            for _ in range(width):
                if i >= len(lines): break
                row = lines[i].strip().split()
                try: matrix.append(list(map(float, row[:len(alphabet)])))
                except: pass
                i += 1
            if len(matrix) == width:
                result[motif_id] = "".join(
                    alphabet[int(np.argmax(pos))] for pos in matrix)
        else:
            i += 1
    return result


def hamming(s1: str, s2: str) -> int | None:
    if len(s1) != len(s2): return None
    return sum(c1 != c2 for c1, c2 in zip(s1, s2))

