def clean_motif_name(x: str) -> str:
    """Remove numeric prefixes from STREME: '24-DEGEMTEEEKK' -> 'DEGEMTEEEKK'"""
    x = str(x).strip()
    x = re.sub(r"^\d+[-_]", "", x)
    return x.strip()


