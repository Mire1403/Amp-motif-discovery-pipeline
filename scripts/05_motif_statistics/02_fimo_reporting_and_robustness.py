# =====================================================
# MAIN
# =====================================================

def main() -> None:
    args = parse_args()
    out_dir = PROJECT_ROOT / (
        "results/06_motif_statistics_test/02_fimo_reporting"
        if args.test else
        "results/06_motif_statistics/02_fimo_reporting"
    )
    setup_logging(out_dir)
    logger.info("FIMO reporting started.  alpha=%.3f  er_min=%.1f  top_n=%d",
                args.alpha, args.er_min, args.top_n)

    # load
    df_raw   = load_enrichment_table()
    hc       = load_fimo_hit_counts()
    logger.info("Hit counts loaded: %d entries", len(hc))

    # normalize
    df = normalize(df_raw, hc, args.alpha, args.er_min)
    df_sig = df[df["Significant"]].copy()
    logger.info("Total motifs: %d  |  Significant: %d", len(df), len(df_sig))

    # analyses
    summary, class_df    = analysis_summary(df)
    exact_ov, sim_ov     = analysis_overlap(df_sig, args.max_mm)
    length_stats         = analysis_length_meme_vs_streme(df)

    # save tables
    master_out = out_dir / "fimo_reporting_master.xlsx"
    with pd.ExcelWriter(master_out, engine="openpyxl") as w:
        df.to_excel(w,        sheet_name="All_normalized",  index=False)
        df_sig.to_excel(w,    sheet_name="Significant",     index=False)
        summary.to_excel(w,   sheet_name="Summary",         index=False)
        class_df.to_excel(w,  sheet_name="Motif_classes",   index=False)
        exact_ov.to_excel(w,  sheet_name="Overlap_exact",   index=False)
        sim_ov.to_excel(w,    sheet_name="Overlap_similar", index=False)
        length_stats.to_excel(w, sheet_name="Length_stats", index=False)
        # GraphPad sheets — flatten MultiIndex columns before writing
        gp_hit = df_sig.pivot_table(index="Motif", columns=["Clustering","Tool"],
                           values="AMP_hit_pct", aggfunc="mean")
        gp_hit.columns = ["_".join(map(str,c)) for c in gp_hit.columns]
        gp_hit.reset_index().to_excel(w, sheet_name="GP_AMP_hit_pct", index=False)

        gp_er = df_sig.pivot_table(index="Motif", columns=["Clustering","Tool"],
                           values="log2_ER", aggfunc="mean")
        gp_er.columns = ["_".join(map(str,c)) for c in gp_er.columns]
        gp_er.reset_index().to_excel(w, sheet_name="GP_log2ER", index=False)
        for cl in df["Clustering"].unique():
            for tl in ["meme","streme"]:
                sub = df[(df["Clustering"]==cl) & (df["Tool"]==tl) &
                         df["Significant"]]["Motif_length"]
                if not sub.empty:
                    pd.DataFrame({"Motif_length": sub.values}).to_excel(
                        w, sheet_name=f"GP_len_{cl[:4]}_{tl[:4]}", index=False)
    logger.info("Master Excel saved: %s", master_out)

    # figures
    fig_significant_bar(summary, out_dir)
    fig_top_motifs(df_sig, args.top_n, out_dir)
    fig_scatter_er_fdr(df_sig, out_dir)
    fig_class_stacked(class_df, out_dir)
    fig_top_hit_frequency(df_sig, args.top_n, out_dir)
    fig_length_meme_vs_streme(df, length_stats, out_dir)

    logger.info("FIMO reporting completed successfully.")
    logger.info("Outputs: %s", out_dir)

if __name__ == "__main__":
    main()