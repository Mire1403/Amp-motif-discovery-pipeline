def normalize(df: pd.DataFrame, hit_counts: pd.DataFrame,
              alpha: float, er_min: float) -> pd.DataFrame:
    df = df.copy()
    # rename columns for consistency
    rename = {"FDR": "FDR_corrected", "Fisher_p": "Fisher_pvalue",
               "Fisher_OR": "Fisher_oddsratio", "AMP_hits": "AMP_sequences_with_hit",
               "nonAMP_hits": "nonAMP_sequences_with_hit",
               "Total_AMP": "Total_AMP_sequences",
               "Total_nonAMP": "Total_nonAMP_sequences",
               "FDR_global": "FDR_corrected_global", "Sig_FDR": "Sig_FDR_local",
               "Sig_FDR_global": "Significant_FDR"}
    df = df.rename(columns={k: v for k, v in rename.items() if k in df.columns})

    for col in ["Clustering","Tool","Motif"]:
        df[col] = df[col].astype(str).str.strip().str.lower()
    # standardize mmseq -> mmseqs for consistency
    df["Clustering"] = df["Clustering"].str.replace(r"^mmseq$", "mmseqs", regex=True)
    df["Motif"] = df["Motif"].map(clean_motif_name)

    # FDR column to use
    if "FDR_corrected_global" in df.columns:
        df["FDR_report"] = pd.to_numeric(df["FDR_corrected_global"], errors="coerce")
    elif "FDR_corrected" in df.columns:
        df["FDR_report"] = pd.to_numeric(df["FDR_corrected"], errors="coerce")
    else:
        raise ValueError("No FDR column found.")

    for col in ["AMP_sequences_with_hit","nonAMP_sequences_with_hit",
                "Total_AMP_sequences","Total_nonAMP_sequences",
                "Enrichment_ratio","Fisher_pvalue"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    df["ER_infinite"] = (
        df.get("nonAMP_sequences_with_hit", pd.Series(dtype=float)).fillna(0).eq(0) &
        df.get("AMP_sequences_with_hit",    pd.Series(dtype=float)).fillna(0).gt(0)
    )

    finite_er = df["Enrichment_ratio"].replace([np.inf,-np.inf], np.nan)
    df["log2_ER"]   = np.log2(finite_er.clip(lower=1e-12))
    df["log10_ER"]  = np.log10(finite_er.clip(lower=1e-12))
    df["neg_log10_FDR"] = -np.log10(df["FDR_report"].clip(lower=1e-300))

    df["Motif_length"] = df["Motif"].str.len()
    df["Motif_class"]  = df["Motif"].map(classify_motif)

    df["Significant"] = (df["FDR_report"] < alpha) & (df["Enrichment_ratio"] > er_min)

    # merge hit counts
    if not hit_counts.empty:
        hc = hit_counts.copy()
        for col in ["Clustering","Tool","Motif"]:
            hc[col] = hc[col].astype(str).str.strip().str.lower()
        hc["Motif"] = hc["Motif"].map(clean_motif_name)
        # force plain str dtype to avoid Arrow/object mismatch
        for col in ["Clustering","Tool","Motif"]:
            df[col] = df[col].astype(str)
            hc[col] = hc[col].astype(str)
        df = df.merge(
            hc[["Clustering","Tool","Motif","Total_hits","AMP_hit_pct"]],
            on=["Clustering","Tool","Motif"], how="left")
    else:
        df["Total_hits"] = np.nan
        df["AMP_hit_pct"] = np.nan

    return df.dropna(subset=["Clustering","Tool","Motif","FDR_report"])

