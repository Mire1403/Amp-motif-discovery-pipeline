def fig_length_meme_vs_streme(df: pd.DataFrame, length_stats: pd.DataFrame,
                               out_dir: Path) -> None:
    """KDE + boxplot comparing motif lengths MEME vs STREME."""
    sig = df[df["Significant"]].copy()
    if sig.empty: return

    clusterings = sig["Clustering"].unique()
    fig, axes = plt.subplots(len(clusterings), 2,
                              figsize=(12, 4*len(clusterings)))
    if len(clusterings) == 1:
        axes = [axes]
    fig.patch.set_facecolor("#fafafa")

    for i, cl in enumerate(sorted(clusterings)):
        meme   = sig[(sig["Clustering"]==cl) & (sig["Tool"]=="meme")]["Motif_length"].dropna()
        streme = sig[(sig["Clustering"]==cl) & (sig["Tool"]=="streme")]["Motif_length"].dropna()

        # KDE panel
        ax_kde = axes[i][0]; ax_kde.set_facecolor("#fafafa")
        if len(meme) > 1:
            sns.kdeplot(meme, fill=True, alpha=0.5,
                        color=PALETTE.get(f"{cl}_meme", "#E07B54"),
                        label=f"MEME (n={len(meme)}, mean={meme.mean():.1f})",
                        ax=ax_kde)
        if len(streme) > 1:
            sns.kdeplot(streme, fill=True, alpha=0.5,
                        color=PALETTE.get(f"{cl}_streme", "#C0504D"),
                        label=f"STREME (n={len(streme)}, mean={streme.mean():.1f})",
                        ax=ax_kde)

        # annotate p-value if available
        row = length_stats[length_stats["Clustering"]==cl]
        if not row.empty:
            p = row["p_mannwhitney"].values[0]
            d = row["Cohen_d"].values[0]
            ax_kde.annotate(
                f"Mann-Whitney p={p:.3e}\nCohen d={d:.3f}",
                xy=(0.05, 0.90), xycoords="axes fraction",
                fontsize=8,
                bbox=dict(boxstyle="round,pad=0.3", fc="white", ec="#ddd"))

        ax_kde.set_xlabel("Motif length (aa)", fontsize=9)
        ax_kde.set_ylabel("Density", fontsize=9)
        ax_kde.set_title(f"{cl.upper()} — Length KDE: MEME vs STREME",
                          fontweight="bold", fontsize=10)
        ax_kde.legend(fontsize=8)
        ax_kde.spines[["top","right"]].set_visible(False)

        # boxplot panel
